"""Regenerate the notation-highlight test fixture from the real pipeline.

Why this script exists
----------------------
``frontend/tests/notation-highlight.test.mjs`` runs the real OSMD bundle against real
MusicXML and asserts that every note in the app's timeline can be found on the page.
For that to mean anything, the MusicXML and the note timeline in the fixture have to be
the *same run's* output. They were not: the fixture was produced once by hand, and
because it is a file in the repository nothing forces it to match the code that
generates it. That is precisely how a fixture came to contain a score whose every
measure spanned the wrong number of ticks while the test suite stayed green.

So the fixture is generated, not curated. Re-run this after changing the arrangement
or the MusicXML writer:

    python scripts/make_notation_fixture.py

It writes ``frontend/tests/fixtures/score.musicxml`` and ``notes.json``. Both come from
one :func:`generate_score` call, so they cannot disagree with each other, and the
MusicXML comes from the writer the app actually uses.

The audio is the same 30 s piano cover every other measurement in this project uses.
It is deliberately the hardest case for the highlight: 星辰大海 at L4 puts both hands on
94 of its notated positions, which is what made ``(bar, beat)`` alone an insufficient
key.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
REPO = BACKEND.parent
sys.path.insert(0, str(BACKEND / "src"))

from services.score.service import ScoreRequest, generate_score  # noqa: E402

#: The real material every other measurement in this project is taken from.
DEFAULT_AUDIO = REPO / "cache" / "audio" / "cde3a16bbb536a15661e1f25efc98ca059dbde2c.wav"

#: Long enough to include the pickup bar and several full bars, short enough that the
#: test stays fast. 30 s at this tempo is 17 bars.
DEFAULT_SECONDS = 30.0

FIXTURE_DIR = REPO / "frontend" / "tests" / "fixtures"


def main(argv: list[str]) -> int:
    audio = Path(argv[1]) if len(argv) > 1 else DEFAULT_AUDIO
    seconds = float(argv[2]) if len(argv) > 2 else DEFAULT_SECONDS
    if not audio.exists():
        print(f"audio not found: {audio}", file=sys.stderr)
        return 1

    print(f"generating a fixture from {audio.name}, first {seconds:g}s", flush=True)
    result = generate_score(
        audio,
        ScoreRequest(
            fidelity="transcribed",
            difficulty=4,
            title="星辰大海 (notation fixture)",
            preview_seconds=seconds,
            # The fixture is the two text files below; rendering a piano track and
            # writing score files next to them would add nothing to this test.
            write_files=False,
        ),
    )

    score = result.score
    FIXTURE_DIR.mkdir(parents=True, exist_ok=True)
    (FIXTURE_DIR / "score.musicxml").write_text(result.musicxml, encoding="utf-8")

    notes = score.note_timeline()
    payload = {
        "_comment": (
            "Generated by backend_python/scripts/make_notation_fixture.py - do not edit. "
            "These notes and this MusicXML are one run's output; if they disagree the "
            "highlight cannot match the page."
        ),
        "beatsPerBar": score.beats_per_bar,
        "tempoBpm": round(score.tempo_bpm, 3),
        "phaseSeconds": round(score.phase_seconds, 4),
        "divisions": score.divisions,
        "measureCount": len(score.measures),
        "noteCount": len(notes),
        "notes": notes,
    }
    (FIXTURE_DIR / "notes.json").write_text(
        # Trailing newline, because the repository's whitespace hook adds one and a
        # generated file that always trips a linter is indistinguishable from a
        # generated file that is subtly wrong.
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    both_hands = len(notes) - len({(n["bar"], n["beat"]) for n in notes})
    print(
        f"wrote {len(score.measures)} bars, {len(notes)} notes "
        f"({both_hands} of them sharing a bar and beat with another hand) to {FIXTURE_DIR}",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
